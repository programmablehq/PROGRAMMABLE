import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const source = new URL("../../ops/project-platform/schema-v1.sql", import.meta.url);
const target = new URL("../../lib/custom-ai/platform/schema.generated.ts", import.meta.url);
const sql = await readFile(source, "utf8");
const hash = createHash("sha256").update(sql).digest("hex");
const generated = `// Generated by scripts/custom-ai/build-platform-schema.mjs. Do not edit.\nexport const PROJECT_PLATFORM_SCHEMA_HASH = "sha256:${hash}";\nexport const PROJECT_PLATFORM_SCHEMA = ${JSON.stringify(sql)};\n`;
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== generated) throw new Error("Project platform schema output is stale");
} else await writeFile(target, generated);
