import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../../../', import.meta.url)).replace(/\/$/, '');
const dir = root + '/packages/launch/contracts/launch-protection-v1';
const write = process.argv.includes('--write');
const names = ['ProtectedNative30HookV1', 'ProtectedNativeInitializerV1', 'ProtectedLaunchTokenV1',
  'LaunchProtectionModuleV1', 'EthereumNativeFeeVaultV3'];
const sourceOf = name => `src/${name === 'EthereumNativeFeeVaultV3' ? 'ethereum-native30-v3' : 'launch-protection'}/${name}.sol`;
const sha = value => 'sha256:' + createHash('sha256').update(value).digest('hex');
let inputText = readFileSync(dir + '/standard-json.json', 'utf8');
const input = JSON.parse(inputText);
if (write) {
  for (const [sourcePath, source] of Object.entries(input.sources)) source.content = readFileSync(root + '/contracts/' + sourcePath, 'utf8');
  inputText = JSON.stringify(input, null, 2) + '\n';
  writeFileSync(dir + '/standard-json.json', inputText);
}
for (const [path, source] of Object.entries(input.sources)) {
  if (readFileSync(root + '/contracts/' + path, 'utf8') !== source.content) throw Error('Source differs: ' + path);
}
const solc = process.env.SOLC ?? homedir() + '/.solc-select/artifacts/solc-0.8.26/solc-0.8.26';
if (!execFileSync(solc, ['--version'], { encoding: 'utf8' }).includes('0.8.26+commit.8a97fa7a')) throw Error('Wrong compiler');
const compileInput = structuredClone(input);
compileInput.settings.outputSelection['*']['*'] = [...new Set([...compileInput.settings.outputSelection['*']['*'], 'metadata'])];
const output = JSON.parse(execFileSync(solc, ['--standard-json'], { input: JSON.stringify(compileInput), encoding: 'utf8', maxBuffer: 32_000_000 }));
const errors = (output.errors ?? []).filter(e => e.severity === 'error');
if (errors.length) throw Error(JSON.stringify(errors));
const immutableNames = new Map();
function visit(node) {
  if (!node || typeof node !== 'object') return;
  if (node.nodeType === 'VariableDeclaration' && node.mutability === 'immutable') immutableNames.set(String(node.id), node.name);
  for (const v of Object.values(node)) { if (Array.isArray(v)) v.forEach(visit); else visit(v); }
}
Object.values(output.sources).forEach(source => visit(source.ast));
function emit(path, value) {
  if (write) { mkdirSync(dir, { recursive: true }); writeFileSync(path, value); }
  else if (readFileSync(path, 'utf8') !== value) throw Error('Generated artifact differs: ' + path);
}
const recipe = { sourceArtifactHash: sha(inputText),
  sourcePropertyRef: 'ProtectedNative30HookV1; exact Standard JSON in packages/launch/contracts/launch-protection-v1',
  recipient: '0xD88539d3c4C460136a733A3Fd60cf6BF269079da' };
const roles = ['hook', 'initializer', 'token', 'module', 'vault'];
for (const [index, name] of names.entries()) {
  const c = output.contracts[sourceOf(name)][name];
  const immutableWords = Object.entries(c.evm.deployedBytecode.immutableReferences).map(([id, refs]) => ({
    name: immutableNames.get(id), byteOffsets: refs.map(ref => ref.start),
  })).sort((a, b) => a.name.localeCompare(b.name));
  if (immutableWords.some(word => !word.name)) throw Error('Unknown immutable');
  const runtime = { runtimeTemplateHex: '0x' + c.evm.deployedBytecode.object, immutableWords };
  recipe[roles[index]] = runtime;
  emit(dir + '/' + name + '.artifact.json', JSON.stringify({ contractName: name, compiler: '0.8.26+commit.8a97fa7a',
    sourcePath: sourceOf(name), sourceArtifactHash: recipe.sourceArtifactHash, abi: c.abi,
    metadata: c.metadata, bytecode: c.evm.bytecode, deployedBytecode: c.evm.deployedBytecode,
    immutableIds: Object.fromEntries(Object.keys(c.evm.deployedBytecode.immutableReferences).map(id => [immutableNames.get(id), id])),
    creationBytecode: '0x' + c.evm.bytecode.object, ...runtime }, null, 2) + '\n');
}
emit(root + '/lib/launch-protection/recipes-v1.ts',
  '/** Generated by packages/launch/scripts/build-launch-protection-v1.mjs. */\nexport const LAUNCH_PROTECTION_RECIPES_V1 = '
  + JSON.stringify({ protected_native30_v1: recipe }, null, 2) + ' as const;\n');
console.log(JSON.stringify({ sourceArtifactHash: recipe.sourceArtifactHash, contracts: names }));
